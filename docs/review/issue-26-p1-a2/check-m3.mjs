import fs from 'node:fs/promises';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { createHash } from 'node:crypto';
import assert from 'node:assert/strict';
const { chromium } = await import(process.env.NEBULA_PLAYWRIGHT ? pathToFileURL(process.env.NEBULA_PLAYWRIGHT).href : 'playwright');
const out = fileURLToPath(new URL('./', import.meta.url));
const sourceBytes = await fs.readFile(new URL('../../../exchange/m3/graph.json', import.meta.url));
const sha = bytes => createHash('sha256').update(bytes).digest('hex');
const source = JSON.parse(sourceBytes), checks = [], consoleEvents = [], requests = [];
const browser = await chromium.launch({ channel: 'msedge', headless: true });
const context = await browser.newContext({ viewport: { width: 1600, height: 900 }, deviceScaleFactor: 1 });
const page = await context.newPage();
page.on('pageerror', e => consoleEvents.push(e.message));
page.on('console', m => { if (['error', 'warning'].includes(m.type())) consoleEvents.push(m.text()); });
page.on('response', async response => { if (response.url().endsWith('/m3-graph.json')) requests.push({ url: response.url(), status: response.status(), sha256: sha(await response.body()) }); });
const check = (name, passed, evidence) => { checks.push({ name, passed, evidence }); assert.ok(passed, name); };
const stats = async () => JSON.parse(await page.locator('#stats').innerText());
async function settle() { await page.waitForTimeout(1200); }
async function screenshot(name) { await page.screenshot({ path: `${out}/m3-${name}.png`, scale: 'css' }); }
try {
  await page.goto('http://127.0.0.1:18127/?diagnostics=1&still=1', { waitUntil: 'networkidle' });
  await page.waitForFunction(() => document.querySelector('#universe').dataset.ready === 'true');
  await page.addStyleTag({ content: '#diagnostics{display:none!important}' }); await settle();
  const initial = await stats(), graph = JSON.parse(await page.locator('#universe').getAttribute('data-graph'));
  check('browser consumes exact formal snapshot bytes', graph.sha256 === sha(sourceBytes) && requests[0]?.sha256 === sha(sourceBytes), requests);
  check('real nodes/edges and decorative particles use independent counts', initial.nodes === 7845 && initial.edges === 11412 && initial.particles === 214200, initial);
  check('M3 mode does not invent demo families', await page.locator('.sector').count() === 0);
  await screenshot('overview');
  await page.locator('#graph-query').fill('skill:python'); await settle();
  await page.locator('#graph-results').selectOption('skill:python'); await settle();
  const selected = await stats();
  check('search selection is an actual raw ID and leaves camera unchanged', selected.selected === 'skill:python' && JSON.stringify(selected.camera) === JSON.stringify(initial.camera), selected);
  const detail = await page.locator('#graph-detail pre').innerText();
  const sourceIndex = source.nodes.findIndex(node => node.id === 'skill:python');
  check('detail provides exact node raw fields and edge indices', detail.includes(`nodes[${sourceIndex}]`) && detail.includes('REQUIRES') && detail.includes('edges['), { sourceIndex, id: selected.selected });
  await screenshot('selected');
  await page.locator('#show-related').click(); await settle();
  const focused = await stats();
  const neighborIds = new Set(['skill:python']);
  const neighborEdges = source.edges.filter(edge => edge.source === 'skill:python' || edge.target === 'skill:python');
  neighborEdges.forEach(edge => { neighborIds.add(edge.source); neighborIds.add(edge.target); });
  const inducedEdges = source.edges.filter(edge => neighborIds.has(edge.source) && neighborIds.has(edge.target));
  check('all one-hop nodes and induced edges retain real source counts', focused.visibleNodes === neighborIds.size && focused.visibleEdges === inducedEdges.length && focused.highlightedEdges === neighborEdges.length, focused);
  await screenshot('neighbors');
  await page.locator('#galaxy').hover({ position: { x: 800, y: 720 } }); await page.mouse.wheel(0, -240); await settle();
  const zoomed = await stats();
  check('selected wheel zooms without changing dust speed', zoomed.distance < focused.distance && zoomed.speed === focused.speed, zoomed); await screenshot('zoom');
  await page.locator('#clear-filter').click(); await page.locator('#node-kind').selectOption('job'); await settle();
  const jobs = await stats();
  check('hidden skill selection clears; node-kind filter is induced', jobs.selected === null && jobs.visibleNodes === 717 && jobs.visibleEdges === 7, jobs);
  await screenshot('jobs');
  await page.locator('#graph-query').fill('no-such-test-node-261018'); await settle();
  const empty = await stats(); check('empty result is genuinely empty', empty.visibleNodes === 0 && empty.visibleEdges === 0 && empty.selected === null, empty);
  await page.locator('#clear-filter').click(); await page.locator('#edge-kind').selectOption('APPLIES_TO'); await settle();
  const industries = await stats(); check('relationship filter preserves all raw APPLIES_TO edges', industries.visibleEdges === 2539, industries);
  await page.locator('#clear-filter').click();
  await page.locator('#run-checks').evaluate(button => button.click());
  await page.waitForFunction(() => document.querySelector('#diagnostics').dataset.finished === 'true', null, { timeout: 60000 });
  const interactions = JSON.parse(await page.locator('#diagnostics').getAttribute('data-checks'));
  check('existing camera/input/resize interactions work with actual M3', interactions.length >= 24 && interactions.every(c => c.passed), interactions);
  await page.evaluate(() => document.dispatchEvent(new Event('visibilitychange')));
  await page.waitForFunction(() => { try { return JSON.parse(document.querySelector('#stats').textContent).frameSamples >= 300; } catch { return false; } }, null, { timeout: 60000 });
  const performance = await stats(); await fs.writeFile(`${out}/m3-performance.json`, JSON.stringify(performance, null, 2));
  // These are explicit fail-closed tests; expected network/parse errors are kept separate.
  const failurePage = await context.newPage();
  const expectedErrors = []; failurePage.on('pageerror', e => expectedErrors.push(e.message)); failurePage.on('console', m => { if (m.type() === 'error') expectedErrors.push(m.text()); });
  await failurePage.route('**/m3-graph.json', route => route.fulfill({ status: 503, body: 'unavailable' }));
  await failurePage.goto('http://127.0.0.1:18127/'); await failurePage.locator('#failure').waitFor({ state: 'visible' });
  check('missing snapshot displays error and never marks graph ready', (await failurePage.locator('#failure').innerText()).includes('503') && await failurePage.locator('#universe').getAttribute('data-ready') === null, expectedErrors);
  await failurePage.unrouteAll();
  await failurePage.route('**/m3-graph.json', route => route.fulfill({ contentType: 'application/json', body: '{"nodes":[{"id":"x","type":"bad"}],"edges":[]}' }));
  await failurePage.reload(); await failurePage.locator('#failure').waitFor({ state: 'visible' });
  check('invalid snapshot never silently substitutes synthetic entities', await failurePage.locator('#universe').getAttribute('data-ready') === null);
  await failurePage.close();
  await page.goto('http://127.0.0.1:18127/?data=demo&diagnostics=1'); await settle();
  const demo = await stats(); check('explicit old data adapter rollback works', demo.nodes === 116 && demo.edges === 40 && demo.provenance.mode === 'synthetic-demo', demo);
  check('normal M3 and demo sessions have no console errors/warnings', consoleEvents.length === 0, consoleEvents);
  await fs.writeFile(`${out}/m3-browser-checks.json`, JSON.stringify({ checks, consoleEvents, expectedErrors, requests, sourceSha256: sha(sourceBytes) }, null, 2));
  console.log(JSON.stringify({ passed: checks.length, performance }));
} finally { await context.close(); await browser.close(); }
